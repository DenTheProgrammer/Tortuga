export const dicts: Record<string, Dict> = { ru, en };

export type T = (k: Key) => string;

export const I18nContext = createContext<{ t: T; lang: string }>({
  t: (k) => ru[k],
  lang: "ru",
});

export function useT() {
  return useContext(I18nContext);
}

/** UI language before settings load: Russian for Russian systems, English otherwise. */
export function systemLang(): string {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function makeT(lang: string): T {
  const d = dicts[lang] ?? en;
  return (k) => d[k] ?? k;
}
